#!/usr/bin/env python3
"""Regenerate docs/checks.md from the check registry.

The provenance of a check -- the incident that caused it to exist -- lives next
to the check, in its decorator. Writing it down twice would let the two drift,
and the provenance is the part that makes a finding worth reading, so it is
generated rather than maintained.

    python3 tools/generate_checks_doc.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from appstore_preflight.checks import load_all  # noqa: E402

HEADER = """# The checks, and why each one exists

<!-- Generated by tools/generate_checks_doc.py. Edit the check's decorator in
     appstore_preflight/checks/, not this file. -->

Every check below states what it asserts and, in one line, why it exists.
Several say plainly that nothing went wrong to justify them and that they are
inference from Apple's documented behaviour. Those are the ones to trust least.

The reasons come from one developer's apps. They are not a survey of what gets
apps rejected, and a check that fired for them may never fire for you.

Checks marked **needs App Store Connect** issue GET requests against the API
and report as skipped, naming what was missing, when no credentials are
configured.

"""


def main() -> int:
    registry = load_all()
    out = [HEADER, f"{len(registry)} checks.\n\n---\n\n"]
    for entry in registry:
        out.append(f"## `{entry.name}`\n\n")
        if entry.needs_network:
            out.append("**needs App Store Connect**\n\n")
        out.append(f"**Asserts:** {entry.summary}\n\n")
        out.append("**Why it exists:**\n\n")
        for paragraph in (entry.incident or "No provenance recorded.").split("\n\n"):
            out.append(f"{paragraph.strip()}\n\n")
        out.append("---\n\n")

    target = Path(__file__).resolve().parent.parent / "docs" / "checks.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("".join(out))
    print(f"wrote {target} ({len(registry)} checks)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
